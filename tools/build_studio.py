# -*- coding: utf-8 -*-
"""Builds studiosource.lua from source.lua.

source.lua is the only file anyone edits. This prepends a compatibility shim,
cuts the Spotify code (it needs request(), which no Studio script has) and
writes studiosource.lua, so the rest of the library body is identical in both
builds and cannot drift.

    python tools/build_studio.py
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

SRC = os.path.join(ROOT, 'source.lua')
OUT = os.path.join(ROOT, 'studiosource.lua')

SHIM = '''-- KyriLib, Roblox Studio build. GENERATED by tools/build_studio.py, do not edit.
-- Edit source.lua and rebuild, or your change is gone on the next build.
--
-- Paste this whole file into a ModuleScript and require it:
--   local kyri = require(game.ReplicatedStorage.KyriLib)
--   local w = kyri.new("my hub")
--
-- loadstring does not work in Studio LocalScripts, so there is no HttpGet
-- one-liner here. The ModuleScript is the way in.
--
-- Saving: nothing persists until you name a DataStore.
--   kyri.persist("MyHubSaves")
-- On the server that writes straight to the DataStore. On a client it needs the
-- bridge from tools/KyriStoreServer.lua in ServerScriptService, because
-- DataStoreService refuses to answer anything but the server. Without either it
-- stays in memory and dies with the playtest. kyri.persist returns false and a
-- reason when it cannot save, so you can check.
--
-- Spotify is not in this build. It needs request(), which no Studio script has.

KYRI_STUDIO = true

do
    local RunService = game:GetService("RunService")
    local ReplicatedStorage = game:GetService("ReplicatedStorage")

    local files, folders = {}, {}
    local store_name, ds, remote
    local dirty, flushing = false, false

    -- the icon cache is 24KB of asset ids that refetch fine, so it stays local
    local function persisted(p)
        return p:sub(-5) == ".json" and p ~= "KyriLib/icons.json"
    end

    local function mark_folders(p)
        local dir = p:match("^(.*)/[^/]+$")
        while dir do
            folders[dir] = true
            dir = dir:match("^(.*)/[^/]+$")
        end
    end

    if not isfile then
        isfile = function(p) return files[p] ~= nil end
        readfile = function(p) return files[p] end
        delfile = function(p)
            files[p] = nil
            if persisted(p) then dirty = true end
        end
        isfolder = function(p) return folders[p] == true end
        makefolder = function(p) folders[p] = true end
        listfiles = function(p)
            local out = {}
            for k in pairs(files) do
                if k:sub(1, #p + 1) == p .. "/" then out[#out + 1] = k end
            end
            return out
        end
        writefile = function(p, d)
            files[p] = d
            mark_folders(p)
            if persisted(p) then dirty = true end
        end
    end

    if not getgenv then
        getgenv = function() return shared end
    end

    local function snapshot()
        local out = {}
        for k, v in pairs(files) do
            if persisted(k) then out[k] = v end
        end
        return out
    end

    local function push()
        local snap = snapshot()
        if ds then
            return pcall(function() ds:SetAsync("kyrilib", snap) end)
        elseif remote then
            return pcall(function() return remote:InvokeServer("set", store_name, snap) end)
        end
        return false
    end

    local function pull()
        local data
        if ds then
            local ok, got = pcall(function() return ds:GetAsync("kyrilib") end)
            if ok then data = got end
        elseif remote then
            local ok, got = pcall(function() return remote:InvokeServer("get", store_name) end)
            if ok then data = got end
        end
        if type(data) ~= "table" then return end
        for k,v in pairs(data) do
            if type(k) == "string" and type(v) == "string" then
                files[k] = v
                mark_folders(k)
            end
        end
    end

    KYRI_SET_STORE = function(name)
        store_name = name or "KyriLib"
        ds, remote = nil, nil

        if RunService:IsServer() then
            local ok, got = pcall(function()
                return game:GetService("DataStoreService"):GetDataStore(store_name)
            end)
            if not ok then
                return false, "datastores are off, tick Studio Access to API Services in Game Settings"
            end
            ds = got
        else
            remote = ReplicatedStorage:FindFirstChild("KyriStore")
            if not remote then
                return false, "no KyriStore RemoteFunction, add tools/KyriStoreServer.lua to ServerScriptService"
            end
        end

        pull()

        if not flushing then
            flushing = true
            task.spawn(function()
                while task.wait(7) do
                    if dirty then
                        dirty = false
                        push()
                    end
                end
            end)
            if RunService:IsServer() then
                game:BindToClose(function()
                    if dirty then push() end
                end)
            end
        end

        return true
    end

    KYRI_FLUSH_STORE = function()
        if not (ds or remote) then return false, "call kyri.persist(name) first" end
        dirty = false
        return push()
    end
end

'''

STUB_SPOTIFY = '''-- spotify is executor only, it needs request(). every call is a no-op here.
function kyri.spotify()
    local sp = {ready = false, playing = false, studio = true}
    return setmetatable(sp, {__index = function() return function() return false end end})
end
'''

STUB_W_SPOTIFY = '''    function w:spotify()
        w:notify("spotify", "spotify needs an executor, it is not in the studio build", 4)
        return kyri.spotify()
    end
'''


def cut(body, begin, end, replacement, label):
    i = body.find(begin)
    j = body.find(end)
    if i < 0 or j < 0:
        print('missing %s markers in source.lua' % label)
        sys.exit(1)
    return body[:i] + replacement + body[j + len(end):]


def main():
    if not os.path.isfile(SRC):
        print('missing %s' % SRC)
        return 1

    raw = open(SRC, 'rb').read().decode('utf8')
    nl = '\r\n' if raw.count('\r\n') else '\n'
    body = raw.replace('\r\n', '\n')

    if 'KYRI_STUDIO' not in body:
        print('source.lua no longer checks KYRI_STUDIO, the shim marker is dead')
        return 1

    body = cut(body, '--[[kyri:spotify-begin]]', '--[[kyri:spotify-end]]',
               STUB_SPOTIFY.rstrip('\n'), 'spotify')
    body = cut(body, '    --[[kyri:wspotify-begin]]', '    --[[kyri:wspotify-end]]',
               STUB_W_SPOTIFY.rstrip('\n'), 'w:spotify')

    tail = '\nreturn kyri'
    if not body.rstrip('\n').endswith(tail.strip()):
        print('source.lua does not end in "return kyri"')
        return 1

    inject = (
        '\n'
        'kyri.persist = KYRI_SET_STORE\n'
        'kyri.flush = KYRI_FLUSH_STORE\n'
        '\n'
        'return kyri\n'
    )
    body = body.rstrip('\n')
    body = body[:body.rindex('return kyri')] + inject.lstrip('\n')

    out = SHIM + body
    open(OUT, 'wb').write(out.replace('\n', nl).encode('utf8'))

    print('wrote %s (%d lines, %d cut from source)'
          % (os.path.basename(OUT), out.count('\n') + 1,
             raw.count('\n') - body.count('\n')))
    return 0


if __name__ == '__main__':
    sys.exit(main())
