# -*- coding: utf-8 -*-
"""Builds studiosource.lua from source.lua.

source.lua is the only file anyone edits. This prepends a compatibility shim
that stands in for the executor globals Studio does not have, so the library
body itself is identical in both builds.

    python tools/build_studio.py
"""

import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

SRC = os.path.join(ROOT, 'source.lua')
OUT = os.path.join(ROOT, 'studiosource.lua')

SHIM = '''-- KyriLib, Roblox Studio build. GENERATED by tools/build_studio.py, do not edit.
-- Edit source.lua and rebuild, or your change is gone on the next build.
--
-- Paste this whole file into a ModuleScript and require it:
--   local kyri = require(game.ReplicatedStorage.KyriLib)
--   local w = kyri.new("my hub")
--
-- loadstring does not work in Studio LocalScripts, so there is no HttpGet
-- one-liner here. The ModuleScript is the way in.
--
-- What is different from the executor build:
--   configs and saved positions live in memory and die with the playtest
--   tab icons need HttpService, which only answers on the server
--   spotify needs request(), which no Studio script has, so it stays idle

KYRI_STUDIO = true

do
    local files, folders = {}, {}

    if not isfile then
        isfile = function(p) return files[p] ~= nil end
        readfile = function(p) return files[p] end
        writefile = function(p, d) files[p] = d end
        delfile = function(p) files[p] = nil end
        isfolder = function(p) return folders[p] == true end
        makefolder = function(p) folders[p] = true end
        listfiles = function(p)
            local out = {}
            for k in pairs(files) do
                if k:sub(1, #p + 1) == p .. "/" then out[#out + 1] = k end
            end
            return out
        end
    end

    if not getgenv then
        getgenv = function() return shared end
    end
end

'''


def main():
    if not os.path.isfile(SRC):
        print('missing %s' % SRC)
        return 1

    raw = open(SRC, 'rb').read().decode('utf8')
    nl = '\r\n' if raw.count('\r\n') else '\n'
    body = raw.replace('\r\n', '\n')

    out = SHIM + body

    if 'KYRI_STUDIO' not in body:
        print('source.lua no longer checks KYRI_STUDIO, the shim marker is dead')
        return 1

    open(OUT, 'wb').write(out.replace('\n', nl).encode('utf8'))
    print('wrote %s (%d lines)' % (os.path.basename(OUT), out.count('\n') + 1))
    return 0


if __name__ == '__main__':
    sys.exit(main())
